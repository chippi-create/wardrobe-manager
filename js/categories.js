export const MERCARI = {
  'レディース': LADIES,
  'メンズ': MENS,
  'ベビー・キッズ': KIDS,
};
export const TOPS = Object.keys(MERCARI);

export function kindOf(top, mid, leaf) {
  const node = MERCARI[top]?.[mid];
  if (!node) return null;
  return node.leafKinds?.[leaf] ?? node.kind;
}

export function categoryPath(item) {
  return [item.mercariTop, item.mercariMid, item.mercariLeaf].filter(Boolean).join(' > ');
}

// 旧バージョン（カテゴリ8種類）からの移行用
const LEGACY = {
  'トップス': ['tops', 'トップス'],
  'アウター': ['outer', 'ジャケット/アウター'],
  'ボトムス': ['bottoms', 'パンツ'],
  'ワンピース': ['onepiece', 'ワンピース'],
  'シューズ': ['shoes', '靴'],
  'バッグ': ['bag', 'バッグ'],
  'アクセサリー': ['accessory', 'アクセサリー'],
  'その他': ['other', 'その他'],
};
export function fromLegacyCategory(category, top) {
  const [kind, mid] = LEGACY[category] ?? ['other', 'その他'];
  return { kind, mercariMid: MERCARI[top]?.[mid] ? mid : '' };
}

